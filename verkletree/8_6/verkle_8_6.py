"""BLS12-381 KZG-committed 8-ary, depth-6 Verkle baseline (262,144 keys).

At EACH level the interpolation points are continuous GLOBAL indices:
  records: 0..262143, groups of 8 consecutive global indices
  next layer node commitments: 0..32767, groups of 8 consecutive global indices
  every level has a continuous index range; root children 0..b-1.
No parent node resets its evaluation points to 0..4.

This uses the original 8^6 Merkle baseline's key generation and H(key,text)
encoding, mapping SHA-256 outputs to the BLS12-381 SCALAR field.

SRS is experimental (not trusted ceremony). Local pickle files are trusted
only if generated by this program. KZG is not post-quantum.
"""

import argparse
import hashlib
import json
import os
import pickle
import time
from pathlib import Path
import sys

# Reuse the original verkletree/kzg.py one directory above this configuration.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import kzg
import merkle_8_6 as merkle
from py_ecc.bls.point_compression import compress_G1, decompress_G1

BASE = Path(__file__).resolve().parent
JSONL = BASE / "leaf_values_8_6.jsonl"
SNAPSHOT = BASE / "verkle_tree_8_6.pkl"
FANOUT = 8
DEPTH = 6
LEAVES = FANOUT ** DEPTH
MODULUS = kzg.R
POINT_BYTES = 48


def point_to_bytes(pt):
    """Canonical compressed BLS12-381 G1 encoding (48 bytes)."""
    return int(compress_G1(pt)).to_bytes(POINT_BYTES, "big")


def bytes_to_point(encoded):
    if not isinstance(encoded, bytes) or len(encoded) != POINT_BYTES:
        raise ValueError("Malformed compressed G1 point")
    return decompress_G1(int.from_bytes(encoded, "big"))


def record_to_field(key, text):
    """SHA256(0x02 || key13 || text_len4 || UTF8(text)) interpreted mod r."""
    return int.from_bytes(merkle.derive_value(key, text), "big") % MODULUS


def commitment_to_field(commitment_bytes):
    """Hash the encoded child KZG commitment into the scalar field."""
    return int.from_bytes(
        hashlib.sha256(b"\x04" + commitment_bytes).digest(), "big"
    ) % MODULUS


def multiply_by_linear(coeffs, a):
    """Multiply polynomial (ascending coefficients) by (X-a) over F_r."""
    out = [0] * (len(coeffs) + 1)
    for i, v in enumerate(coeffs):
        out[i] = (out[i] - a * v) % MODULUS
        out[i + 1] = (out[i + 1] + v) % MODULUS
    return out


def interpolate(xs, ys):
    """Lagrange interpolation over F_r; xs need not start at zero."""
    if len(xs) != len(ys) or not xs or len(set(xs)) != len(xs):
        raise ValueError("Expected equal-length vectors with distinct x")
    coeffs = [0] * len(xs)
    for i, (xi, yi) in enumerate(zip(xs, ys)):
        numerator = [1]
        denominator = 1
        for j, xj in enumerate(xs):
            if i == j:
                continue
            numerator = multiply_by_linear(numerator, xj)
            denominator = denominator * (xi - xj) % MODULUS
        weight = yi * pow(denominator, -1, MODULUS) % MODULUS
        for j, coefficient in enumerate(numerator):
            coeffs[j] = (coeffs[j] + weight * coefficient) % MODULUS
    if any(kzg.evaluate(coeffs, x) != y % MODULUS for x, y in zip(xs, ys)):
        raise AssertionError("Interpolation failed")
    return coeffs


def build_node(level, group, ys, srs_g1):
    if len(ys) != FANOUT:
        raise ValueError("Wrong number of node evaluations")
    start = group * FANOUT
    xs = list(range(start, start + FANOUT))
    coeffs = interpolate(xs, ys)
    return {
        "level": level,
        "group": group,
        "xs": xs,
        "coeffs": coeffs,
        "commitment": point_to_bytes(kzg.commit(coeffs, srs_g1)),
    }


def build_levels(keys, texts, srs_g1):
    values = [record_to_field(k, t) for k, t in zip(keys, texts)]
    levels = []
    for level in range(DEPTH):
        if len(values) % FANOUT:
            raise AssertionError("Incomplete node group")
        total_nodes = len(values) // FANOUT
        nodes = []
        next_values = []
        for j in range(total_nodes):
            node = build_node(level, j, values[j * FANOUT:(j + 1) * FANOUT], srs_g1)
            nodes.append(node)
            next_values.append(commitment_to_field(node["commitment"]))
            if total_nodes >= 10_000 and (j + 1) % 10_000 == 0:
                print(f"  KZG level {level}: {j+1:,}/{total_nodes:,} commitments constructed", flush=True)
        levels.append(nodes)
        print(f"Level {level}: {len(nodes):,} KZG commitments, global x=0..{len(values)-1:,}", flush=True)
        values = next_values
    if [len(x) for x in levels] != [FANOUT ** (DEPTH - j - 1) for j in range(DEPTH)]:
        raise AssertionError("Unexpected node count")
    return levels


def read_jsonl():
    with JSONL.open(encoding="utf-8") as f:
        values = [json.loads(line) for line in f]
    if len(values) != LEAVES or not all(isinstance(s, str) for s in values):
        raise ValueError("JSONL must contain exactly LEAVES JSON-encoded strings")
    return values


def validate(state, texts):
    """Independently check records, all KZG polynomials/commitments, root and SRS."""
    if (state["fanout"], state["depth"], state["n"], state["curve"]) != (
        FANOUT, DEPTH, LEAVES, "BLS12-381"
    ):
        raise ValueError("Wrong tree configuration")
    keys = state["keys"]
    if (len(keys) != LEAVES or keys != sorted(set(keys))
            or any(not 1 <= k <= merkle.KEY_UNIVERSE for k in keys)):
        raise ValueError("Invalid key sequence")
    if state["key_to_index"] != {k: i for i, k in enumerate(keys)}:
        raise ValueError("Key index mismatch")
    if len(texts) != LEAVES:
        raise ValueError("Wrong number of lines")
    g1 = state["srs_g1"]
    if len(g1) != FANOUT:
        raise ValueError("SRS degree != 4")
    current = [record_to_field(k, t) for k, t in zip(keys, texts)]
    for level, nodes in enumerate(state["levels"]):
        if len(nodes) * FANOUT != len(current):
            raise ValueError("Incorrect node count")
        next_values = []
        for j, node in enumerate(nodes):
            xs = list(range(j * FANOUT, (j + 1) * FANOUT))
            if node["xs"] != xs or node["level"] != level or node["group"] != j:
                raise ValueError("Non-continuous or incorrect node evaluation points")
            ys = current[j * FANOUT:(j + 1) * FANOUT]
            if len(node["coeffs"]) != FANOUT:
                raise ValueError("Unexpected polynomial length")
            if [kzg.evaluate(node["coeffs"], z) for z in xs] != ys:
                raise ValueError("Polynomial evaluations do not match children")
            recomputed = point_to_bytes(kzg.commit(node["coeffs"], g1))
            if node["commitment"] != recomputed:
                raise ValueError("Invalid stored KZG commitment")
            next_values.append(commitment_to_field(recomputed))
        current = next_values
    if [len(x) for x in state["levels"]] != [FANOUT ** (DEPTH - j - 1) for j in range(DEPTH)]:
        raise ValueError("Bad tree shape")
    if state["root"] != state["levels"][-1][0]["commitment"]:
        raise ValueError("Root commitment does not match highest node")
    return True


def construct_or_load(rebuild=False):
    if SNAPSHOT.exists() and not rebuild:
        if not JSONL.exists():
            raise FileNotFoundError("Snapshot exists but JSONL is missing")
        with SNAPSHOT.open("rb") as f:
            state = pickle.load(f)  # Only locally generated trusted snapshots!
        texts = read_jsonl()
        validate(state, texts)
        print("Loaded and independently validated the stored Verkle tree.")
        return state, texts
    if JSONL.exists() or SNAPSHOT.exists():
        if not rebuild:
            raise FileExistsError("Partial existing dataset; inspect files or use --rebuild")
    print(f"Generating {LEAVES:,} distinct random sorted keys (original Merkle generator)...", flush=True)
    started = time.perf_counter()
    keys = merkle.generate_keys(LEAVES)
    texts = [f"this is leaf {i+1}" for i in range(LEAVES)]
    t_gen = time.perf_counter() - started

    print(f"Generating experimental degree-{FANOUT-1} BLS12-381 KZG SRS...", flush=True)
    started = time.perf_counter()
    srs_g1, srs_g2 = kzg.setup(max_degree=FANOUT-1)
    t_srs = time.perf_counter() - started

    print(f"Interpolating polynomials and committing all {sum(FANOUT**j for j in range(DEPTH)):,} nodes...", flush=True)
    started = time.perf_counter()
    levels = build_levels(keys, texts, srs_g1)
    t_build = time.perf_counter() - started
    state = {
        "version": 1, "curve": "BLS12-381", "fanout": FANOUT, "depth": DEPTH,
        "n": LEAVES, "keys": keys, "key_to_index": {k:i for i,k in enumerate(keys)},
        "levels": levels, "root": levels[-1][0]["commitment"],
        "srs_g1": srs_g1, "srs_g2": srs_g2,
        "evaluation_points": "consecutive global positions within each level",
        "leaf_values": "int(SHA256(0x02||key13||len4||UTF8(line))) mod BLS12-381.r",
        "parent_values": "int(SHA256(0x04||compressed(child_commitment))) mod r",
    }
    started = time.perf_counter()
    validate(state, texts)
    t_validate = time.perf_counter() - started
    with JSONL.open("w", encoding="utf-8", newline="\n") as f:
        for t in texts:
            f.write(json.dumps(t) + "\n")
        f.flush()
        os.fsync(f.fileno())
    with SNAPSHOT.open("wb") as f:
        pickle.dump(state, f, protocol=pickle.HIGHEST_PROTOCOL)
        f.flush()
        os.fsync(f.fileno())
    print("Reloading pickle and validating all commitments...", flush=True)
    loaded, loaded_texts = construct_or_load(rebuild=False)
    print(f"Construction: key generation {t_gen:.3f}s; SRS {t_srs:.3f}s; "
          f"{sum(FANOUT**j for j in range(DEPTH)):,} KZG commitments {t_build:.3f}s; validation {t_validate:.3f}s")
    print(f"Tree root (compressed G1): {state['root'].hex()}")
    print(f"Saved JSONL {JSONL.stat().st_size} bytes, pickle {SNAPSHOT.stat().st_size} bytes")
    return loaded, loaded_texts


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--rebuild", action="store_true", help="replace locally generated 8_6 files")
    args = ap.parse_args()
    construct_or_load(args.rebuild)
    print("PASS: independently validated full Verkle 8^6 snapshot")


if __name__ == "__main__":
    main()
